/* eslint-disable no-console */

import * as fs from 'fs';
import * as path from 'path';

/**
 * Script to test which country codes from the database have Intl translation support.
 * This will determine the standard vs extended country code sets.
 */

interface Country {
  id: number;
  name: string;
  iso3: string;
  iso2: string;
  numeric_code: string;
  phonecode: string;
  capital: string;
  currency: string;
  currency_name: string;
  currency_symbol: string;
  tld: string;
  native: string;
  population: number;
  gdp: number | null;
  region: string;
  region_id: number;
  subregion: string;
  subregion_id: number;
  latitude: string;
  longitude: string;
  emoji: string;
  emojiU: string;
}

const WORKSPACE_ROOT = process.cwd();
const SOURCES_DIR = path.join(WORKSPACE_ROOT, 'sources', 'countries-states-cities-database', 'json');
const OUTPUT_DIR = path.join(WORKSPACE_ROOT, 'libs', 'standards', 'src', 'lib', 'codes');

function loadCountriesData(): Country[] {
  const countriesPath = path.join(SOURCES_DIR, 'countries.json');
  
  if (!fs.existsSync(countriesPath)) {
    throw new Error(`Countries file not found: ${countriesPath}`);
  }

  console.log('Loading countries data...');
  const countries: Country[] = JSON.parse(fs.readFileSync(countriesPath, 'utf8'));
  console.log(`Loaded ${countries.length} countries`);
  
  return countries;
}

function testIntlTranslationSupport(countries: Country[]): {
  standard: string[];
  extended: string[];
  unsupported: string[];
} {
  console.log('Testing Intl translation support for all country codes...');
  
  const standard: string[] = [];
  const extended: string[] = [];
  const unsupported: string[] = [];
  
  // Test with English locale
  const displayNames = new Intl.DisplayNames(['en'], { type: 'region' });
  
  countries.forEach(country => {
    const code = country.iso2;
    if (!code) return;
    
    try {
      const translatedName = displayNames.of(code);
      
      if (translatedName && translatedName !== code) {
        // Intl provides a translation
        standard.push(code);
        console.log(`✅ STANDARD: ${code} (${country.name}) → ${translatedName}`);
      } else {
        // No translation available - use database name as fallback
        extended.push(code);
        console.log(`🔶 EXTENDED: ${code} (${country.name}) - no Intl translation`);
      }
    } catch (error) {
      unsupported.push(code);
      console.log(`❌ ERROR: ${code} (${country.name}) - ${(error as Error).message}`);
    }
  });
  
  console.log(`\n📊 Results:`);
  console.log(`  Standard (has Intl translation): ${standard.length}`);
  console.log(`  Extended (no Intl translation, use database name): ${extended.length}`);
  console.log(`  Error (Intl error): ${unsupported.length}`);
  console.log(`  Total tested: ${countries.length}`);
  
  return { standard, extended, unsupported };
}

function generateCountryCodesFile(standard: string[], extended: string[], unsupported: string[]): void {
  const outputPath = path.join(OUTPUT_DIR, 'country-codes.ts');
  
  const content = `/**
 * CountryCodes provides access to country codes with Intl translation support.
 * 
 * STANDARD: ${standard.length} countries with Intl translation support
 * EXTENDED: ${extended.length} countries without Intl translations (use database names)
 * ERROR: ${unsupported.length} countries with Intl errors
 * 
 * Generated by tools/scripts/test-intl-country-support.ts
 * Last updated: ${new Date().toISOString()}
 */

export class CountryCodes {
  private static _standardCache?: readonly string[];
  private static _extendedCache?: readonly string[];
  private static _allCache?: readonly string[];

  /**
   * Returns standard country codes (has Intl translation support).
   * Cached on first access.
   */
  static get standard(): readonly string[] {
    if (!this._standardCache) {
      this._standardCache = Object.freeze([
${standard.map(code => `        '${code}'`).join(',\n')}
      ]);
    }
    return this._standardCache;
  }

  /**
   * Returns extended country codes (no Intl translation, use database names).
   * Cached on first access.
   */
  static get extended(): readonly string[] {
    if (!this._extendedCache) {
      this._extendedCache = Object.freeze([
${extended.map(code => `        '${code}'`).join(',\n')}
      ]);
    }
    return this._extendedCache;
  }

  /**
   * Returns all country codes (standard + extended).
   * Cached on first access.
   */
  static get all(): readonly string[] {
    if (!this._allCache) {
      this._allCache = Object.freeze([...this.standard, ...this.extended]);
    }
    return this._allCache;
  }

  /**
   * Checks if a country code is valid.
   * @param code - The country code to validate
   * @param options - Validation options
   * @returns true if the code is valid in the specified set
   */
  static isValid(code: string, options?: { extended?: boolean }): boolean {
    if (!code || typeof code !== 'string') {
      return false;
    }
    
    const normalizedCode = code.toUpperCase();
    
    if (options?.extended) {
      return this.all.includes(normalizedCode);
    } else {
      return this.standard.includes(normalizedCode);
    }
  }

  /**
   * Converts a country code to its canonical uppercase form.
   * @param code - The country code to normalize
   * @param options - Validation options
   * @returns The canonical uppercase country code, or null if invalid
   */
  static toCanonical(code: string, options?: { extended?: boolean }): string | null {
    if (!code || typeof code !== 'string') {
      return null;
    }
    
    const canonical = code.toUpperCase();
    return this.isValid(canonical, options) ? canonical : null;
  }

  /**
   * Gets the localized name for a country code using Intl.DisplayNames.
   * @param code - The country code
   * @param locale - The locale for the translation (defaults to 'en')
   * @returns The localized country name, or null if not supported
   */
  static getLocalizedName(code: string, locale: string = 'en'): string | null {
    if (!this.isValid(code, { extended: true })) {
      return null;
    }
    
    try {
      const displayNames = new Intl.DisplayNames([locale], { type: 'region' });
      const name = displayNames.of(code.toUpperCase());
      return name && name !== code.toUpperCase() ? name : null;
    } catch {
      return null;
    }
  }
}

/**
 * Extended country codes (${extended.length} total):
 * These codes do not have Intl translation support and will use database names.
 * 
${extended.map(code => ` * - ${code}`).join('\n')}
 */

/**
 * Error country codes (${unsupported.length} total):
 * These codes caused errors when testing with Intl.DisplayNames.
 * 
${unsupported.map(code => ` * - ${code}`).join('\n')}
 */
`;

  fs.writeFileSync(outputPath, content);
  console.log(`\n✅ Generated country-codes.ts with ${standard.length} standard + ${extended.length} extended codes`);
}

function main(): void {
  try {
    console.log('🧪 Testing Intl translation support for country codes...\n');
    
    const countries = loadCountriesData();
    const { standard, extended, unsupported } = testIntlTranslationSupport(countries);
    
    generateCountryCodesFile(standard, extended, unsupported);
    
    console.log('\n🎉 Analysis complete!');
    console.log(`📋 Summary:`);
    console.log(`  Standard codes: ${standard.length} (has Intl translation)`);
    console.log(`  Extended codes: ${extended.length} (no Intl translation, use database names)`);
    console.log(`  Error codes: ${unsupported.length} (Intl errors)`);
    
  } catch (error) {
    console.error('❌ Error:', (error as Error).message);
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}
