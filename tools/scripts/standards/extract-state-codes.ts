/* eslint-disable no-console */

import * as fs from 'fs';
import * as path from 'path';

/**
 * Script to extract state codes from the countries-states-cities-database
 * and generate TypeScript files for the @agape/standards package.
 */

interface Country {
  id: number;
  name: string;
  iso3: string;
  iso2: string;
  numeric_code: string;
  phonecode: string;
  capital: string;
  currency: string;
  currency_name: string;
  currency_symbol: string;
  tld: string;
  native: string;
  population: number;
  gdp: number | null;
  region: string;
  region_id: number;
  subregion: string;
  subregion_id: number;
  latitude: string;
  longitude: string;
  emoji: string;
  emojiU: string;
}

interface State {
  id: number;
  name: string;
  country_id: number;
  country_code: string;
  country_name: string;
  iso2: string;
  iso3166_2: string;
  fips_code: string;
  type: string | null;
  level: number | null;
  parent_id: number | null;
  native: string;
  latitude: string;
  longitude: string;
  timezone: string;
}

interface DatabaseData {
  countries: Country[];
  states: State[];
}

const WORKSPACE_ROOT = process.cwd();
const SOURCES_DIR = path.join(WORKSPACE_ROOT, 'sources', 'countries-states-cities-database', 'json');
const STANDARDS_LIB_DIR = path.join(WORKSPACE_ROOT, 'libs', 'standards', 'src', 'lib', 'codes', 'states');
const DEFINITIONS_DIR = path.join(STANDARDS_LIB_DIR, 'definitions');

function ensureDirectoryExists(dirPath: string): void {
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
  }
}

function loadDatabaseData(): DatabaseData {
  const countriesPath = path.join(SOURCES_DIR, 'countries.json');
  const statesPath = path.join(SOURCES_DIR, 'states.json');

  console.log(`Looking for countries file: ${countriesPath}`);
  console.log(`Looking for states file: ${statesPath}`);

  if (!fs.existsSync(countriesPath)) {
    throw new Error(`Countries file not found: ${countriesPath}`);
  }
  if (!fs.existsSync(statesPath)) {
    throw new Error(`States file not found: ${statesPath}`);
  }

  console.log('Loading countries data...');
  const countries: Country[] = JSON.parse(fs.readFileSync(countriesPath, 'utf8'));
  console.log(`Loaded ${countries.length} countries`);

  console.log('Loading states data...');
  const states: State[] = JSON.parse(fs.readFileSync(statesPath, 'utf8'));
  console.log(`Loaded ${states.length} states`);

  return { countries, states };
}

function extractStateCodesByCountry(data: DatabaseData): Map<string, string[]> {
  const stateCodesByCountry = new Map<string, string[]>();

  // Create a map of country ID to ISO2 code
  const countryIdToIso2 = new Map<number, string>();
  data.countries.forEach(country => {
    countryIdToIso2.set(country.id, country.iso2);
  });

  console.log(`Created country ID to ISO2 mapping for ${countryIdToIso2.size} countries`);

  // Group states by country using country_code field
  data.states.forEach(state => {
    const countryCode = state.country_code;
    const stateCode = state.iso2; // Use iso2 field for state codes
    
    if (countryCode && stateCode) {
      if (!stateCodesByCountry.has(countryCode)) {
        stateCodesByCountry.set(countryCode, []);
      }
      const codes = stateCodesByCountry.get(countryCode)!;
      if (!codes.includes(stateCode)) {
        codes.push(stateCode);
      }
    }
  });

  // Sort codes for each country
  stateCodesByCountry.forEach(codes => codes.sort());

  console.log(`Extracted state codes for ${stateCodesByCountry.size} countries`);
  
  // Log some examples
  const examples = Array.from(stateCodesByCountry.entries()).slice(0, 5);
  examples.forEach(([country, codes]) => {
    console.log(`${country}: ${codes.length} states (${codes.slice(0, 3).join(', ')}${codes.length > 3 ? '...' : ''})`);
  });

  return stateCodesByCountry;
}

function generateDefinitionsFile(stateCodesByCountry: Map<string, string[]>): void {
  const definitionsPath = path.join(DEFINITIONS_DIR, 'definitions.ts');

  let content = `/**
 * State code definitions extracted from countries-states-cities-database.
 * Generated by tools/scripts/standards/extract-state-codes.ts
 *
 * Last updated: ${new Date().toISOString()}
 */

`;

  // Sort countries by ISO2 code
  const sortedCountries = Array.from(stateCodesByCountry.entries()).sort(([a], [b]) => a.localeCompare(b));

  sortedCountries.forEach(([countryCode, stateCodes]) => {
    const codesString = stateCodes.map(code => `'${code}'`).join(', ');
    content += `export const ${countryCode} = Object.freeze([${codesString}] as const);\n`;
  });

  fs.writeFileSync(definitionsPath, content);
  console.log(`Generated definitions file: ${definitionsPath}`);
}

function generateCountryFiles(stateCodesByCountry: Map<string, string[]>): void {
  const sortedCountries = Array.from(stateCodesByCountry.entries()).sort(([a], [b]) => a.localeCompare(b));

  sortedCountries.forEach(([countryCode, stateCodes]) => {
    const fileName = countryCode.toLowerCase();
    const filePath = path.join(STANDARDS_LIB_DIR, `${fileName}.ts`);

    const content = `/**
 * State codes for ${countryCode}.
 * Generated by tools/scripts/standards/extract-state-codes.ts
 */

import { StateCodes } from '../state-codes';
import { ${countryCode} } from './definitions/definitions';

StateCodes.register('${countryCode}', ${countryCode});
`;

    fs.writeFileSync(filePath, content);
    console.log(`Generated country file: ${filePath}`);
  });
}

function generateAllFile(stateCodesByCountry: Map<string, string[]>): void {
  const allPath = path.join(STANDARDS_LIB_DIR, 'all.ts');

  let content = `/**
 * All state code registrations.
 * Generated by tools/scripts/standards/extract-state-codes.ts
 *
 * Last updated: ${new Date().toISOString()}
 */

`;

  // Sort countries by ISO2 code
  const sortedCountries = Array.from(stateCodesByCountry.keys()).sort();

  sortedCountries.forEach(countryCode => {
    const fileName = countryCode.toLowerCase();
    content += `import './${fileName}';\n`;
  });

  fs.writeFileSync(allPath, content);
  console.log(`Generated all file: ${allPath}`);
}

function generateCountriesWithoutStatesFile(data: DatabaseData, stateCodesByCountry: Map<string, string[]>): void {
  const countriesWithoutStatesPath = path.join(DEFINITIONS_DIR, 'countries-without-states.ts');

  // Get all country codes from the database
  const allCountryCodes = data.countries
    .map(country => country.iso2)
    .filter(code => code && code.length === 2)
    .sort();

  // Get countries that have states
  const countriesWithStates = Array.from(stateCodesByCountry.keys());

  // Find countries without states
  const countriesWithoutStates = allCountryCodes.filter(code => !countriesWithStates.includes(code));

  const content = `/**
 * Countries that have no states/provinces.
 * Generated by tools/scripts/standards/extract-state-codes.ts
 *
 * Last updated: ${new Date().toISOString()}
 */

export const COUNTRIES_WITHOUT_STATES = Object.freeze([
${countriesWithoutStates.map(code => `  '${code}'`).join(',\n')}
] as const);
`;

  fs.writeFileSync(countriesWithoutStatesPath, content);
  console.log(`Generated countries-without-states file: ${countriesWithoutStatesPath}`);
  console.log(`Found ${countriesWithoutStates.length} countries without states`);
}

function generateIndexFile(): void {
  const indexPath = path.join(STANDARDS_LIB_DIR, 'index.ts');

  const content = `/**
 * State code definitions exports.
 * Generated by tools/scripts/standards/extract-state-codes.ts
 */

export * from './definitions/definitions';
`;

  fs.writeFileSync(indexPath, content);
  console.log(`Generated index file: ${indexPath}`);
}

function updatePackageJsonExports(stateCodesByCountry: Map<string, string[]>): void {
  const packageJsonPath = path.join(WORKSPACE_ROOT, 'libs', 'standards', 'package.json');
  const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));

  // Add dynamic exports for each country
  const sortedCountries = Array.from(stateCodesByCountry.keys()).sort();

  sortedCountries.forEach(countryCode => {
    const fileName = countryCode.toLowerCase();
    const exportKey = `./codes/states/${fileName}`;

    packageJson.exports[exportKey] = {
      "es2022": `./es2022/lib/codes/states/${fileName}.js`,
      "node": `./cjs/lib/codes/states/${fileName}.js`,
      "default": `./es2022/lib/codes/states/${fileName}.js`,
      "require": `./cjs/lib/codes/states/${fileName}.js`,
      "import": `./es2022/lib/codes/states/${fileName}.js`
    };
  });

  fs.writeFileSync(packageJsonPath, JSON.stringify(packageJson, null, 2));
  console.log(`Updated package.json exports`);
}

function main(): void {
  try {
    console.log('Starting state codes extraction...');

    // Ensure directories exist
    ensureDirectoryExists(STANDARDS_LIB_DIR);
    ensureDirectoryExists(DEFINITIONS_DIR);

    // Load and process data
    console.log('Loading database data...');
    const data = loadDatabaseData();

    console.log('Extracting state codes by country...');
    const stateCodesByCountry = extractStateCodesByCountry(data);

    console.log(`Found ${stateCodesByCountry.size} countries with state codes`);

    // Generate files
    console.log('Generating TypeScript files...');
    generateDefinitionsFile(stateCodesByCountry);
    generateCountriesWithoutStatesFile(data, stateCodesByCountry);
    generateCountryFiles(stateCodesByCountry);
    generateAllFile(stateCodesByCountry);
    generateIndexFile();

    // Update package.json exports
    console.log('Updating package.json exports...');
    updatePackageJsonExports(stateCodesByCountry);

    console.log('State codes extraction completed successfully!');

  } catch (error) {
    console.error('Error during extraction:', error);
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}