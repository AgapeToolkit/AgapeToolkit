/* eslint-disable no-console */

import { execSync } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';

/**
 * Script to download/update the Unicode CLDR repository and extract locale codes
 */

const WORKSPACE_ROOT = process.cwd();
const SOURCES_DIR = path.join(WORKSPACE_ROOT, 'sources');
const CLDR_DIR = path.join(SOURCES_DIR, 'cldr-json');
const CLDR_LOCALES_DIR = path.join(CLDR_DIR, 'cldr-json', 'cldr-localenames-full', 'main');
const LOCALES_LIB_DIR = path.join(WORKSPACE_ROOT, 'libs', 'standards', 'src', 'lib', 'locales');
const REPO_URL = 'git@github.com:unicode-org/cldr-json.git';

function ensureDirectoryExists(dirPath: string): void {
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
  }
}

function isGitRepository(dirPath: string): boolean {
  return fs.existsSync(path.join(dirPath, '.git'));
}

function downloadCLDR(): void {
  console.log('Starting CLDR download/update...');
  
  // Ensure sources directory exists
  ensureDirectoryExists(SOURCES_DIR);
  
  if (isGitRepository(CLDR_DIR)) {
    console.log('CLDR repository exists, updating...');
    try {
      // Update existing repository
      execSync('git pull origin main', { 
        cwd: CLDR_DIR,
        stdio: 'inherit'
      });
      console.log('CLDR repository updated successfully');
    } catch (error) {
      console.error('Failed to update CLDR repository:', error);
      throw error;
    }
  } else {
    console.log('CLDR repository not found, cloning...');
    try {
      // Clone the repository
      execSync(`git clone ${REPO_URL} "${CLDR_DIR}"`, {
        stdio: 'inherit'
      });
      console.log('CLDR repository cloned successfully');
    } catch (error) {
      console.error('Failed to clone CLDR repository:', error);
      throw error;
    }
  }
  
  // Verify the required directory exists
  if (!fs.existsSync(CLDR_LOCALES_DIR)) {
    throw new Error(`Required directory not found: ${CLDR_LOCALES_DIR}`);
  }
  
  console.log('CLDR locales directory verified');
}

function extractLocaleCodes(): string[] {
  console.log('Extracting locale codes from CLDR...');
  
  if (!fs.existsSync(CLDR_LOCALES_DIR)) {
    throw new Error(`CLDR locales directory not found: ${CLDR_LOCALES_DIR}`);
  }
  
  const entries = fs.readdirSync(CLDR_LOCALES_DIR, { withFileTypes: true });
  const localeCodes: string[] = [];
  
  entries.forEach(entry => {
    // Only process directories and skip hidden files
    if (entry.isDirectory() && !entry.name.startsWith('.')) {
      localeCodes.push(entry.name);
    }
  });
  
  // Sort alphabetically
  localeCodes.sort();
  
  console.log(`Extracted ${localeCodes.length} locale codes`);
  
  // Log some examples
  const examples = localeCodes.slice(0, 10);
  console.log(`Examples: ${examples.join(', ')}${localeCodes.length > 10 ? '...' : ''}`);
  
  return localeCodes;
}

function filterSupportedLocales(localeCodes: string[]): string[] {
  console.log('Filtering locales for runtime support...');
  
  const supportedLocales: string[] = [];
  
  localeCodes.forEach(locale => {
    try {
      const formatter = new Intl.DateTimeFormat(locale);
      const resolvedLocale = formatter.resolvedOptions().locale;
      
      // Only include if resolved locale exactly matches input
      if (resolvedLocale === locale) {
        supportedLocales.push(locale);
      }
    } catch {
      // Locale throws error, skip it
    }
  });
  
  console.log(`Filtered ${localeCodes.length} locales down to ${supportedLocales.length} runtime-supported locales`);
  
  return supportedLocales;
}

function generateDefinitionsFile(localeCodes: string[]): void {
  const definitionsPath = path.join(LOCALES_LIB_DIR, 'definitions.ts');
  
  console.log(`Generating definitions file: ${definitionsPath}`);
  
  const content = `/**
 * Runtime-supported locale code definitions from Unicode CLDR.
 * Filtered to include only locales exactly supported by Intl.DateTimeFormat.
 * Generated by tools/scripts/standards/extract-locales.ts
 *
 * Last updated: ${new Date().toISOString()}
 * Total locales: ${localeCodes.length}
 */

export const LOCALE_CODES = Object.freeze([
${localeCodes.map(code => `  '${code}'`).join(',\n')}
] as const);
`;
  
  fs.writeFileSync(definitionsPath, content);
  console.log(`Generated definitions file with ${localeCodes.length} locale codes`);
}

function saveMetadata(): void {
  try {
    const commitHash = execSync('git rev-parse HEAD', { 
      cwd: CLDR_DIR,
      encoding: 'utf8'
    }).trim();
    
    const commitDate = execSync('git log -1 --format=%ci', { 
      cwd: CLDR_DIR,
      encoding: 'utf8'
    }).trim();
    
    console.log(`Latest CLDR commit: ${commitHash}`);
    console.log(`Commit date: ${commitDate}`);
    
    // Save metadata
    const metadata = {
      lastUpdated: new Date().toISOString(),
      commitHash,
      commitDate,
      repository: REPO_URL,
      source: 'cldr-localenames-full/main'
    };
    
    const metadataPath = path.join(SOURCES_DIR, 'cldr-metadata.json');
    fs.writeFileSync(metadataPath, JSON.stringify(metadata, null, 2));
    console.log(`Metadata saved to: ${metadataPath}`);
    
  } catch (error) {
    console.warn('Could not get CLDR commit information:', error);
  }
}

function main(): void {
  try {
    console.log('Starting locale codes extraction...');
    
    // Ensure directories exist
    ensureDirectoryExists(LOCALES_LIB_DIR);
    
    // Download/update CLDR repository
    downloadCLDR();
    
    // Extract locale codes
    const localeCodes = extractLocaleCodes();
    
    // Filter to only runtime-supported locales
    const supportedLocales = filterSupportedLocales(localeCodes);
    
    // Generate definitions file
    generateDefinitionsFile(supportedLocales);
    
    // Save metadata
    saveMetadata();
    
    console.log('Locale codes extraction completed successfully!');
    console.log(`Generated files in: ${LOCALES_LIB_DIR}`);
    
  } catch (error) {
    console.error('Error during locale codes extraction:', error);
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}
