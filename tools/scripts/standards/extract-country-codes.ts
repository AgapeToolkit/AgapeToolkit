/* eslint-disable no-console */

import * as fs from 'fs';
import * as path from 'path';

const WORKSPACE_ROOT = process.cwd();
const SOURCES_DIR = path.join(WORKSPACE_ROOT, 'sources', 'countries-states-cities-database', 'json');
const COUNTRIES_LIB_DIR = path.join(WORKSPACE_ROOT, 'libs', 'standards', 'src', 'lib', 'codes', 'countries');

interface Country {
  id: number;
  name: string;
  iso3: string;
  iso2: string;
  numeric_code: string;
  phonecode: string;
  capital: string;
  currency: string;
  currency_name: string;
  currency_symbol: string;
  tld: string;
  native: string;
  population: number;
  gdp: number | null;
  region: string;
  region_id: number;
  subregion: string;
  subregion_id: number;
  latitude: string;
  longitude: string;
  emoji: string;
  emojiU: string;
}

function ensureDirectoryExists(dirPath: string): void {
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
  }
}

function loadCountriesData(): Country[] {
  const countriesPath = path.join(SOURCES_DIR, 'countries.json');
  if (!fs.existsSync(countriesPath)) {
    throw new Error(`Countries file not found: ${countriesPath}`);
  }
  console.log(`Loading countries data from: ${countriesPath}`);
  const countries: Country[] = JSON.parse(fs.readFileSync(countriesPath, 'utf8'));
  console.log(`Loaded ${countries.length} countries`);
  return countries;
}

function loadStandardCodes(): string[] {
  const standardPath = path.join(COUNTRIES_LIB_DIR, 'standard.ts');
  if (!fs.existsSync(standardPath)) {
    throw new Error(`Standard codes file not found: ${standardPath}`);
  }
  
  // Read the file and extract the array
  const content = fs.readFileSync(standardPath, 'utf8');
  const match = content.match(/export const STANDARD_COUNTRY_CODES = Object\.freeze\(\[([\s\S]*?)\]\)/);
  if (!match) {
    throw new Error('Could not parse STANDARD_COUNTRY_CODES from standard.ts');
  }
  
  const codesString = match[1];
  const codes = codesString
    .split(',')
    .map(code => code.trim().replace(/['"]/g, ''))
    .filter(code => code.length === 2);
  
  console.log(`Loaded ${codes.length} standard country codes`);
  return codes;
}

function generateExtendedFile(allCodes: string[], standardCodes: string[]): void {
  const extendedPath = path.join(COUNTRIES_LIB_DIR, 'extended.ts');
  
  console.log(`Generating extended file: ${extendedPath}`);
  
  const standardSet = new Set(standardCodes);
  const extendedCodes = allCodes
    .filter(code => !standardSet.has(code))
    .sort();
  
  const content = `/**
 * Extended country codes (territories, dependencies, special regions)
 * Generated from countries-states-cities-database
 * 
 * Generated by tools/scripts/standards/extract-country-codes.ts
 * Last updated: ${new Date().toISOString()}
 */

export const EXTENDED_COUNTRY_CODES = Object.freeze([
${extendedCodes.map(code => `  '${code}'`).join(',\n')}
] as const);
`;
  
  fs.writeFileSync(extendedPath, content);
  console.log(`Generated ${extendedCodes.length} extended country codes`);
  console.log('Extended file generated successfully');
}

function main(): void {
  try {
    console.log('Starting country codes extraction...');
    
    ensureDirectoryExists(COUNTRIES_LIB_DIR);
    
    const countries = loadCountriesData();
    const standardCodes = loadStandardCodes();
    
    // Extract all country codes from database
    const allCodes = countries
      .map(country => country.iso2)
      .filter(code => code && code.length === 2)
      .sort();
    
    generateExtendedFile(allCodes, standardCodes);
    
    console.log('Country codes extraction completed successfully!');
    console.log(`Generated files in: ${COUNTRIES_LIB_DIR}`);
    
  } catch (error) {
    console.error('Error during country codes extraction:', error);
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}